    private static let bits: [Character: [[Bool]]] = raw.mapValues { rows in
        rows.map { row in row.map { $0 == "1" } }
    }

    static func glyph(_ ch: Character) -> [[Bool]] {
        if let g = bits[ch] { return g }
        // normalise smart punctuation, then fall back
        let map: [Character: Character] = ["—": "—", "–": "-", "“": "\"", "”": "\"", "‘": "'", "’": "'", "…": "…"]
        if let alt = map[ch], let g = bits[alt] { return g }
        return bits["?"]!
    }

    static func width(_ text: String) -> CGFloat { CGFloat(text.count) * advance }

    /// Draw at the bottom-left of the first line (AppKit coordinates, y up).
    static func draw(_ text: String, at origin: NSPoint, alpha: CGFloat, color: NSColor = NSColor(calibratedRed: 0.90, green: 0.98, blue: 0.92, alpha: 1)) {
        let ink = color.withAlphaComponent(alpha)
        ink.setFill()
        let unit = max(pixel, 0.01)
        func snap(_ v: CGFloat) -> CGFloat { (v / unit).rounded() * unit }
        var x = snap(origin.x)
        for ch in text {
            let g = glyph(ch)
            for (row, rowBits) in g.enumerated() {
                for (col, on) in rowBits.enumerated() where on {
                    let x0 = snap(x + CGFloat(col) * scale)
                    let x1 = snap(x + CGFloat(col + 1) * scale)
                    let y0 = snap(origin.y + CGFloat(6 - row) * scale)
                    let y1 = snap(origin.y + CGFloat(7 - row) * scale)
                    NSRect(x: x0, y: y0, width: max(unit, x1 - x0), height: max(unit, y1 - y0)).fill()
                }
            }
            x = snap(x + advance)
        }
    }

    /// Headless preview: renders the whole charset to a PNG for eyeballing.
    static func writeTestImage(to path: String) {
        let lines = [
            "ABCDEFGHIJKLM",
            "NOPQRSTUVWXYZ",
            "abcdefghijklm",
            "nopqrstuvwxyz",
            "0123456789",
            "!?.,:;'\"-_()/",
            "BabyZilla is 64px",
            "The quick brown fox",
            "jumps over the lazy",
            "dog. 42% saved.",
        ]
        let step = Int(lineHeight) + 2
        let w = 200, h = lines.count * step + 6
        let rep = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: w, pixelsHigh: h,
                                   bitsPerSample: 8, samplesPerPixel: 4, hasAlpha: true,
                                   isPlanar: false, colorSpaceName: .deviceRGB, bytesPerRow: w * 4, bitsPerPixel: 32)!
        NSGraphicsContext.saveGraphicsState()
        NSGraphicsContext.current = NSGraphicsContext(bitmapImageRep: rep)
        NSColor(calibratedRed: 0.05, green: 0.05, blue: 0.08, alpha: 1).setFill()
        NSRect(x: 0, y: 0, width: w, height: h).fill()
        var y = CGFloat(h) - glyphHeight - 4
        for line in lines {
            draw(line, at: NSPoint(x: 4, y: y), alpha: 1)
            y -= CGFloat(step)
        }
        NSGraphicsContext.restoreGraphicsState()
        let png = rep.representation(using: .png, properties: [:])!
        try? png.write(to: URL(fileURLWithPath: path))
    }
